// Regenerates docs/agent-capabilities.md from docs/agent-capabilities.json. Run with `npm run docs:capabilities`.
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../docs/agent-capabilities.json', import.meta.url), 'utf8'));
const agents = Object.entries(data.agents);
const MARK = { yes: '✅ yes', partial: '🟡 partial', no: '❌ no', unknown: '❔ unknown' };

const cell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s);

/** `how` and `limits` are a string, a list, or one entry per product surface. */
function text(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  if (Array.isArray(v)) return v.map(text).join(' ');
  return Object.entries(v).map(([k, x]) => `${k.replace(/_/g, ' ')}: ${text(x)}`).join(' · ');
}
function bullets(v) {
  if (v == null || v === '') return [];
  if (typeof v === 'string') return [v];
  if (Array.isArray(v)) return v.flatMap(bullets);
  return Object.entries(v).map(([k, x]) => `**${k.replace(/_/g, ' ')}:** ${text(x)}`);
}
const sources = (ev) => ev.filter((e) => e.url).slice(0, 3).map((e, i) => `[${i + 1}](${e.url})`).join(' ');

const out = [
  `# ${data.title}`,
  '',
  '<!-- Generated by scripts/gen-capabilities-doc.mjs from docs/agent-capabilities.json. Edit the JSON, then run `npm run docs:capabilities`. -->',
  '',
  `Seven coding agents, checked against the same 16 questions on ${new Date(data.checked + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' })}: what can a developer, a team or an admin actually make each agent do, or stop it doing, through configuration?`,
  '',
  `**Method.** ${data.method} The full data, with every quote and source, is in [agent-capabilities.json](agent-capabilities.json). Agents change monthly: if something here is out of date, please [open an issue](https://github.com/thinkingraven/rookery/issues/new).`,
  '',
  '## Key findings',
  '',
  '1. **A cloned repo\'s own config is the first thing to check, and agents differ sharply.**',
  '   - **Ignored before you trust the folder:** Claude Code (interactive), Codex, Gemini CLI (current releases), Copilot CLI and VS Code.',
  '   - **Applied on open:** Cursor ships with Workspace Trust off, so a repo\'s hooks, permission allow-lists and sandbox settings apply as soon as you open it. OpenCode has no trust prompt at all.',
  '   - **No trust check in Claude Code\'s `-p` (headless) mode:** a repo\'s hooks and `.mcp.json` servers run even in a folder you\'ve never trusted.',
  '   - **After trust, a repo can turn approvals off in Codex:** `approval_policy = "never"` plus `sandbox_mode = "danger-full-access"`. Since 0.147.0, some Codex flows record a project as trusted without a prompt.',
  '   - **After trust, a repo can\'t turn on bypass or yolo mode in Claude Code, Gemini CLI or Copilot CLI**, though in most agents it can still pre-approve commands or tools and add MCP servers and hooks.',
  '2. **"Deny" often means "ask", and command rules match text.**',
  '   - VS Code\'s `false` terminal rules and Windsurf Cascade\'s deny list only force a prompt, and "Allow all" skips it.',
  '   - Claude Code, Codex, Cursor and Copilot match command text or prefixes, so a wrapper or a different spelling can get round a deny rule.',
  '3. **Read denies rarely stop `cat`.**',
  '   - **With the OS sandbox on, shell reads are stopped too:** Codex (whose permission profiles are enforced by its sandbox), Claude Code and Copilot.',
  '   - **Without a sandbox, the rules cover only the agent\'s own read tool:** Gemini CLI\'s ignore files, `.cursorignore`, OpenCode\'s `read` rules and Windsurf\'s `.devinignore`.',
  '4. **Sandboxes exist almost everywhere but are mostly off by default.**',
  '   - **On by default:** Codex, and Cursor\'s Auto-review mode, which sandboxes commands that aren\'t on the allow-list.',
  '   - **Off by default:** Claude Code, Gemini CLI and Copilot.',
  '   - **Partly or not at all:** Windsurf has one only in Devin Local. OpenCode has none and recommends Docker or a VM.',
  '5. **Admins can lock bypass modes off in most agents, but the lock lives in the client.**',
  '   - **Strongest:** Copilot, with one managed setting across the CLI, VS Code and JetBrains.',
  '   - **Claude Code and Codex:** both have managed locks. Claude\'s server-managed settings aren\'t fetched on Bedrock, Vertex or a custom base URL. Codex\'s cloud policy only reaches ChatGPT sign-ins.',
  '   - **Cursor:** group settings merge with the loosest setting winning.',
  '   - **Windsurf:** caps Cascade only.',
  '   - **Gemini CLI:** its system settings path can be repointed with an environment variable.',
  '   - **OpenCode:** can\'t turn off `--auto`.',
  '6. **Hooks are the one control every agent has, and the command-based ones fail open.**',
  '   - All seven can block a tool call before it runs. OpenCode does it with in-process plugins instead of hook commands.',
  '   - In the other six, a hook that crashes or times out lets the call through by default. Claude Code added `onFailure: "block"` in 2.1.295.',
  '7. **No agent keeps a complete local record of permission decisions.** Every audit-log entry below is partial.',
  '',
  '## The matrix',
  '',
  `| | ${agents.map(([, a]) => a.name).join(' | ')} |`,
  `|---|${agents.map(() => '---').join('|')}|`,
  ...Object.entries(data.capabilities).map(([k, c]) => `| [${c.title}](#${c.title.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) | ${agents.map(([, a]) => MARK[a.capabilities[k].support] ?? a.capabilities[k].support).join(' | ')} |`),
  '',
  `Legend: ${Object.entries(data.support_levels).map(([k, v]) => `${MARK[k]} ${v.charAt(0).toLowerCase() + v.slice(1)}`).join(' · ')}. "Partial" always comes with limits, listed under each capability.`,
  '',
  '## Versions checked',
  '',
  '| Agent | Version and sources |',
  '|---|---|',
  ...agents.map(([, a]) => `| ${a.name} | ${cell(a.version)} |`),
  '',
];

for (const [k, c] of Object.entries(data.capabilities)) {
  out.push(`## ${c.title}`, '', c.description, '', '| Agent | Support | How | Sources |', '|---|---|---|---|');
  for (const [, a] of agents) {
    const v = a.capabilities[k];
    out.push(`| ${a.name} | ${MARK[v.support] ?? v.support} | ${cell(clip(text(v.how), 420))} | ${sources(v.evidence)} |`);
  }
  out.push('', '<details><summary>Limits and caveats</summary>', '');
  for (const [, a] of agents) {
    const lim = bullets(a.capabilities[k].limits);
    if (lim.length) out.push(`**${a.name}**`, '', ...lim.map((l) => `- ${l.replace(/\s*\n\s*/g, ' ')}`), '');
  }
  out.push('</details>', '');
}

writeFileSync(new URL('../docs/agent-capabilities.md', import.meta.url), out.join('\n'));
console.log(`docs/agent-capabilities.md: ${agents.length} agents × ${Object.keys(data.capabilities).length} capabilities`);

// A compact copy for the CLI: support levels only, so `rookery check` can say what each agent can enforce.
const support = Object.fromEntries(agents.map(([id, a]) => [id, { name: a.name, support: Object.fromEntries(Object.entries(a.capabilities).map(([k, v]) => [k, v.support])) }]));
writeFileSync(new URL('../src/policy/capabilities.ts', import.meta.url), [
  '// Generated by scripts/gen-capabilities-doc.mjs from docs/agent-capabilities.json. Do not edit by hand.',
  '',
  "export type Support = 'yes' | 'partial' | 'no' | 'unknown';",
  `export const CAPABILITIES_CHECKED = '${data.checked}';`,
  `export const AGENT_SUPPORT: Record<string, { name: string; support: Record<string, Support> }> = ${JSON.stringify(support, null, 2)};`,
  '',
].join('\n'));
console.log('src/policy/capabilities.ts: support levels for', agents.length, 'agents');
