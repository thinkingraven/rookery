// Regenerates docs/rules.md from the rule definitions. Run with `npm run docs`.
import { writeFileSync } from 'node:fs';
import { ALL_RULES } from '../dist/src/rules.js';

const FAMILIES = [
  ['SEC', 'Secrets', 'Credentials committed inside skills, rules or the scripts bundled with them.'],
  ['EXF', 'Exfiltration', 'Instructions or scripts that send data off the machine.'],
  ['INJ', 'Prompt injection', 'Text that tries to override the agent, hide from the user, or hide from reviewers.'],
  ['EXE', 'Unsafe execution', 'Commands that run untrusted code, destroy data or switch off approval prompts.'],
  ['SUP', 'Supply chain', 'Unverified downloads and unpinned installs.'],
  ['HOOK', 'Hooks', 'Commands the agent runs automatically on events, without anyone asking.'],
  ['PRM', 'Permissions', 'Allow-lists that grant the agent more than it needs.'],
  ['MCP', 'MCP servers', 'How MCP servers are fetched and reached.'],
  ['QLT', 'Quality', 'Problems that make skills hard to find, trigger or afford.'],
];
const BADGE = { critical: '🔴 critical', high: '🟠 high', medium: '🟡 medium', low: '🔵 low', info: '⚪ info' };

const out = [
  '# Rules',
  '',
  `<!-- Generated by scripts/gen-rules-doc.mjs. Edit src/rules.ts, then run \`npm run docs\`. -->`,
  '',
  `Rookery ships ${ALL_RULES.length} static rules. Every rule runs on skill and rule text, on the scripts and references bundled next to a skill, and (where it applies) on agent settings, hooks and MCP configuration.`,
  '',
  '| Rule | Severity | Checks for |',
  '|---|---|---|',
  ...ALL_RULES.map((r) => `| [\`${r.id}\`](#${r.id.toLowerCase()}) | ${r.severity} | ${r.title} |`),
  '',
];
for (const [code, name, blurb] of FAMILIES) {
  const rules = ALL_RULES.filter((r) => r.id.startsWith(`RK-${code}-`));
  if (!rules.length) continue;
  out.push(`## ${name}`, '', blurb, '');
  for (const r of rules) out.push(`### ${r.id}`, '', `**${r.title}** · ${BADGE[r.severity]}`, '', `- **Why it matters:** ${r.why}`, `- **Fix:** ${r.remediation}`, '');
}
out.push(
  '## Confidence',
  '',
  'Security skills, docs and scanners are full of attack examples. A finding is marked **low confidence** when its context shows the pattern is described rather than used:',
  '',
  '- the file is a test, fixture, example or sample (a skill folder\'s own name, like `skills/spec/`, does not count);',
  '- the file is a security reference document (threat models, audits, injection guides);',
  '- the line is a Markdown table row;',
  '- the sentence holding the match warns about it ("never", "don\'t", "e.g.", "for example", "instead of", "malicious"…);',
  '- the match is a string or pattern inside scanner code;',
  '- `sudo` appears in setup instructions in documentation.',
  '',
  'Hidden Unicode, hooks, permissions, MCP and quality findings are always high confidence. Low-confidence findings are reported separately and only count towards `--fail-on` with `--strict`.',
  '',
  '## Suppressing a reviewed line',
  '',
  'Put `rookery-ignore` (all rules) or `rookery-ignore RK-EXE-001 RK-SUP-002` (specific rules) on the line or the line above. Markers from other scanners are honoured too: `noqa`, `nosec`, `gitleaks:allow`, `trufflehog:ignore` and `pragma: allowlist secret`.',
  '',
);
writeFileSync(new URL('../docs/rules.md', import.meta.url), out.join('\n'));
console.log(`docs/rules.md: ${ALL_RULES.length} rules`);
