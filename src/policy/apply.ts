import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Agent } from '../types.js';
import type { Policy } from './policy.js';

/**
 * `rookery policy apply`: write the policy into each agent's own config.
 *
 * Additive and owned: rookery records every value it adds in .rookery/applied.json, so a later run can update or
 * remove its own values and never touches anything a person wrote. Settings only an admin can set go into
 * .rookery/ADMIN.md. Formats follow docs/agent-capabilities.md (checked 2026-10-13).
 */

export const STATE_FILE = '.rookery/applied.json';
export const ADMIN_FILE = '.rookery/ADMIN.md';
const BLOCK_START = '# >>> rookery: generated from .rookery.yml. Edit the policy, not this block.';
const BLOCK_END = '# <<< rookery';

/** Agents apply knows how to configure. */
export const APPLY_AGENTS: Agent[] = ['claude-code', 'codex', 'gemini', 'cursor', 'copilot', 'windsurf'];

type Json = Record<string, unknown>;
interface JsonFileState { kind: 'json'; set: Record<string, unknown>; add: Record<string, string[]>; created: string[]; createdFile?: boolean }
interface BlockFileState { kind: 'block'; createdFile?: boolean }
interface WholeFileState { kind: 'whole' }
type FileState = JsonFileState | BlockFileState | WholeFileState;
export interface ApplyState { version: 1; files: Record<string, FileState> }

export type FileStatus = 'create' | 'update' | 'delete' | 'unchanged';
export interface FileChange { path: string; status: FileStatus; before: string | null; after: string | null; agent?: Agent; notes: string[] }
export interface ApplyPlan { agents: Agent[]; changes: FileChange[]; conflicts: string[]; notes: string[]; state: ApplyState; applied: boolean }

/** What one agent wants in its repo files. */
interface JsonWant { kind: 'json'; path: string; set: Record<string, unknown>; add: Record<string, string[]> }
interface BlockWant { kind: 'block'; path: string; lines: string[] }
interface WholeWant { kind: 'whole'; path: string; content: string | null }
type Want = (JsonWant | BlockWant | WholeWant) & { agent: Agent };

const isHome = (glob: string) => glob.startsWith('~/');
/** never_read entries that name files inside the repo, as gitignore-style lines. */
const repoGlobs = (p: Policy) => p.files.never_read.filter((g) => !isHome(g) && !g.startsWith('/'));
const tokens = (prefix: string) => prefix.trim().split(/\s+/);

function wants(p: Policy, agents: Agent[]): Want[] {
  const out: Want[] = [];
  const bypass = p.approvals.bypass === 'forbid';
  const reads = p.files.read_secrets === 'allow' ? [] : p.files.never_read;
  const mcpAllow = p.mcp.unlisted === 'forbid' ? p.mcp.allow : null;
  const has = (a: Agent) => agents.includes(a);

  if (has('claude-code')) {
    const deny = [...p.shell.deny.flatMap((d) => [`Bash(${d})`, `Bash(${d} *)`]), ...reads.map((g) => `Read(${g})`)];
    const set: Record<string, unknown> = {};
    if (bypass) set['permissions.disableBypassPermissionsMode'] = 'disable';
    if (mcpAllow) set.allowedMcpServers = mcpAllow.map((serverName) => ({ serverName }));
    out.push({ agent: 'claude-code', kind: 'json', path: '.claude/settings.json', set, add: deny.length ? { 'permissions.deny': deny } : {} });
  }
  if (has('codex')) {
    const rules = p.shell.deny.map((d) => `prefix_rule(\n    pattern = [${tokens(d).map((t) => JSON.stringify(t)).join(', ')}],\n    decision = "forbidden",\n    justification = ${JSON.stringify(`Forbidden by .rookery.yml (shell.deny: ${d}).`)},\n)`);
    out.push({ agent: 'codex', kind: 'whole', path: '.codex/rules/rookery.rules', content: rules.length ? `# Generated by \`rookery policy apply\` from .rookery.yml. Edit the policy, not this file.\n\n${rules.join('\n\n')}\n` : null });
  }
  if (has('gemini')) {
    const set: Record<string, unknown> = {};
    if (bypass) set['security.disableYoloMode'] = true;
    if (mcpAllow) set['mcp.allowed'] = mcpAllow;
    const exclude = p.shell.deny.map((d) => `run_shell_command(${d})`);
    out.push({ agent: 'gemini', kind: 'json', path: '.gemini/settings.json', set, add: exclude.length ? { 'tools.exclude': exclude } : {} });
    out.push({ agent: 'gemini', kind: 'block', path: '.geminiignore', lines: reads.length ? repoGlobs(p) : [] });
  }
  if (has('cursor')) {
    const deny = [...p.shell.deny.map((d) => { const [cmd, ...rest] = tokens(d); return rest.length ? `Shell(${cmd}:${rest.join(' ')}*)` : `Shell(${cmd})`; }), ...(reads.length ? repoGlobs(p).map((g) => `Read(${g})`) : [])];
    out.push({ agent: 'cursor', kind: 'json', path: '.cursor/cli.json', set: {}, add: deny.length ? { 'permissions.deny': deny } : {} });
    out.push({ agent: 'cursor', kind: 'block', path: '.cursorignore', lines: reads.length ? repoGlobs(p) : [] });
  }
  if (has('windsurf')) out.push({ agent: 'windsurf', kind: 'block', path: '.devinignore', lines: reads.length ? repoGlobs(p) : [] });
  return out;
}

// --- JSON helpers: dotted paths into nested objects ---------------------------------------------------------------

const segs = (key: string) => key.split('.');
function getAt(o: Json, key: string): unknown {
  let cur: unknown = o;
  for (const k of segs(key)) { if (!cur || typeof cur !== 'object' || Array.isArray(cur)) return undefined; cur = (cur as Json)[k]; }
  return cur;
}
/** Set a value, creating parent objects; returns the parent paths it created. */
function setAt(o: Json, key: string, value: unknown): string[] {
  const parts = segs(key);
  const created: string[] = [];
  let cur = o;
  parts.slice(0, -1).forEach((k, i) => {
    if (!cur[k] || typeof cur[k] !== 'object' || Array.isArray(cur[k])) { cur[k] = {}; created.push(parts.slice(0, i + 1).join('.')); }
    cur = cur[k] as Json;
  });
  cur[parts[parts.length - 1]] = value;
  return created;
}
function deleteAt(o: Json, key: string): void {
  const parts = segs(key);
  const parent = parts.length > 1 ? getAt(o, parts.slice(0, -1).join('.')) : o;
  if (parent && typeof parent === 'object' && !Array.isArray(parent)) delete (parent as Json)[parts[parts.length - 1]];
}
const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);

function planJson(root: string, want: JsonWant, prev: JsonFileState | undefined, conflicts: string[]): { after: string | null; state: JsonFileState | null } {
  const full = join(root, want.path);
  const before = existsSync(full) ? readFileSync(full, 'utf8') : null;
  let doc: Json = {};
  if (before !== null) {
    try {
      const parsed = JSON.parse(before);
      if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error('not an object');
      doc = parsed;
    } catch {
      conflicts.push(`${want.path} is not plain JSON (comments or a syntax error), so rookery won't rewrite it. Add these by hand: ${JSON.stringify({ set: want.set, add: want.add })}`);
      return { after: before, state: prev ?? null };
    }
  }
  // Take back what rookery added last time, but only where it is still exactly what rookery wrote.
  if (prev) {
    for (const [k, v] of Object.entries(prev.set)) if (same(getAt(doc, k), v)) deleteAt(doc, k);
    for (const [k, vals] of Object.entries(prev.add)) {
      const arr = getAt(doc, k);
      if (Array.isArray(arr)) { const left = arr.filter((x) => !vals.includes(x as string)); if (left.length) setAt(doc, k, left); else deleteAt(doc, k); }
    }
    for (const k of [...prev.created].sort((a, b) => b.length - a.length)) { const v = getAt(doc, k); if (v && typeof v === 'object' && !Array.isArray(v) && !Object.keys(v).length) deleteAt(doc, k); }
  }
  const state: JsonFileState = { kind: 'json', set: {}, add: {}, created: [], ...(prev?.createdFile || before === null ? { createdFile: true } : {}) };
  for (const [k, v] of Object.entries(want.set)) {
    const cur = getAt(doc, k);
    if (cur === undefined) { state.created.push(...setAt(doc, k, v)); state.set[k] = v; }
    else if (!same(cur, v)) conflicts.push(`${want.path}: ${k} is ${JSON.stringify(cur)}, but the policy needs ${JSON.stringify(v)}. rookery leaves hand-written values alone; change it yourself.`);
  }
  for (const [k, vals] of Object.entries(want.add)) {
    const cur = getAt(doc, k);
    if (cur !== undefined && !Array.isArray(cur)) { conflicts.push(`${want.path}: ${k} is not a list, so rookery can't add ${vals.join(', ')}.`); continue; }
    const arr = (cur as unknown[] | undefined) ?? [];
    const added = vals.filter((v) => !arr.includes(v));
    if (!added.length) continue;
    if (cur === undefined) state.created.push(...setAt(doc, k, [...added]));
    else setAt(doc, k, [...arr, ...added]);
    state.add[k] = added;
  }
  const owned = Object.keys(state.set).length || Object.keys(state.add).length;
  const empty = !Object.keys(doc).length;
  if (empty && (before === null || state.createdFile)) return { after: null, state: owned ? state : null };
  return { after: JSON.stringify(doc, null, 2) + '\n', state: owned ? state : null };
}

function planBlock(root: string, want: BlockWant, prev: BlockFileState | undefined): { after: string | null; state: BlockFileState | null } {
  const full = join(root, want.path);
  const before = existsSync(full) ? readFileSync(full, 'utf8') : null;
  const text = before ?? '';
  const start = text.indexOf(BLOCK_START);
  const end = start >= 0 ? text.indexOf(BLOCK_END, start) : -1;
  const outside = start >= 0 && end >= 0 ? (text.slice(0, start) + text.slice(end + BLOCK_END.length)).replace(/\n{3,}/g, '\n\n') : text;
  const createdFile = prev?.createdFile || before === null;
  if (!want.lines.length) {
    const rest = outside.replace(/^\s+|\s+$/g, '');
    if (!rest && createdFile) return { after: null, state: null };
    return { after: start >= 0 ? rest + (rest ? '\n' : '') : before, state: null };
  }
  const block = [BLOCK_START, ...want.lines, BLOCK_END].join('\n');
  const base = outside.replace(/\s+$/, '');
  return { after: (base ? base + '\n\n' : '') + block + '\n', state: { kind: 'block', ...(createdFile ? { createdFile: true } : {}) } };
}

function planWhole(root: string, want: WholeWant, prev: WholeFileState | undefined, conflicts: string[]): { after: string | null; state: WholeFileState | null } {
  const full = join(root, want.path);
  const before = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (before !== null && !prev && before !== want.content) {
    conflicts.push(`${want.path} already exists and wasn't written by rookery, so it was left alone.`);
    return { after: before, state: null };
  }
  return { after: want.content, state: want.content ? { kind: 'whole' } : null };
}

export function readState(root: string): ApplyState | null {
  const f = join(root, STATE_FILE);
  if (!existsSync(f)) return null;
  try { const s = JSON.parse(readFileSync(f, 'utf8')); return s && s.version === 1 && s.files ? s : null; } catch { return null; }
}

/** Plan the changes `apply` would make. Nothing is written. */
export function planApply(root: string, policy: Policy, found: Agent[]): ApplyPlan {
  const prevState = readState(root);
  const agents = APPLY_AGENTS.filter((a) => (policy.agents ? policy.agents.includes(a) : found.includes(a)));
  const conflicts: string[] = [];
  const state: ApplyState = { version: 1, files: {} };
  const changes: FileChange[] = [];
  const touched = new Set<string>();
  const record = (path: string, agent: Agent | undefined, after: string | null, notes: string[] = []) => {
    touched.add(path);
    const full = join(root, path);
    const before = existsSync(full) ? readFileSync(full, 'utf8') : null;
    const status: FileStatus = before === after ? 'unchanged' : before === null ? 'create' : after === null ? 'delete' : 'update';
    changes.push({ path, status, before, after, agent, notes });
  };

  for (const w of wants(policy, agents)) {
    const prev = prevState?.files[w.path];
    if (w.kind === 'json') { const r = planJson(root, w, prev?.kind === 'json' ? prev : undefined, conflicts); if (r.state) state.files[w.path] = r.state; record(w.path, w.agent, r.after); }
    else if (w.kind === 'block') { const r = planBlock(root, w, prev?.kind === 'block' ? prev : undefined); if (r.state) state.files[w.path] = r.state; record(w.path, w.agent, r.after); }
    else { const r = planWhole(root, w, prev?.kind === 'whole' ? prev : undefined, conflicts); if (r.state) state.files[w.path] = r.state; record(w.path, w.agent, r.after); }
  }
  // Files rookery wrote before for agents that are no longer in scope: take its values back out.
  for (const [path, prev] of Object.entries(prevState?.files ?? {})) {
    if (touched.has(path)) continue;
    if (prev.kind === 'json') { const r = planJson(root, { kind: 'json', path, set: {}, add: {} }, prev, conflicts); record(path, undefined, r.after); }
    else if (prev.kind === 'block') { const r = planBlock(root, { kind: 'block', path, lines: [] }, prev); record(path, undefined, r.after); }
    else record(path, undefined, null);
  }
  record(ADMIN_FILE, undefined, adminGuide(policy, agents));
  const notes: string[] = [];
  if (policy.mcp.unlisted === 'forbid' && !policy.mcp.allow.length && agents.some((a) => a === 'claude-code' || a === 'gemini')) {
    notes.push('mcp.allow is empty and mcp.unlisted is forbid, so this blocks every MCP server in this repo for Claude Code and Gemini CLI. List the servers you use under mcp.allow, or set mcp.unlisted: allow.');
  }
  // Always recorded on apply, so `check` knows this repo uses apply and can report drift.
  record(STATE_FILE, undefined, JSON.stringify(state, null, 2) + '\n');
  return { agents, changes, conflicts, notes, state, applied: prevState !== null };
}

export function writePlan(root: string, plan: ApplyPlan): number {
  let n = 0;
  for (const c of plan.changes) {
    if (c.status === 'unchanged') continue;
    const full = join(root, c.path);
    if (c.after === null) { if (existsSync(full)) rmSync(full); }
    else { mkdirSync(dirname(full), { recursive: true }); writeFileSync(full, c.after); }
    n++;
  }
  return n;
}

/** Settings that only an admin can make binding, per agent in scope. */
export function adminGuide(p: Policy, agents: Agent[]): string {
  const deny = p.shell.deny;
  const reads = p.files.read_secrets === 'allow' ? [] : p.files.never_read;
  const bypass = p.approvals.bypass === 'forbid';
  const mcp = p.mcp.unlisted === 'forbid' ? p.mcp.allow : null;
  const out: string[] = [
    '# Admin settings for this repo\'s agent policy',
    '',
    '<!-- Generated by `rookery policy apply` from .rookery.yml. Edit the policy, then run apply again. -->',
    '',
    '`rookery policy apply` wrote what each agent accepts from a repo. The settings below can only be made binding by an admin, on each machine or in the vendor\'s admin console, so a person or a cloned repo can\'t switch them off. Sources: [docs/agent-capabilities.md](https://github.com/thinkingraven/rookery/blob/main/docs/agent-capabilities.md).',
    '',
  ];
  const section = (title: string, body: string[]) => { if (body.length) out.push(`## ${title}`, '', ...body, ''); };
  const json = (o: unknown) => ['```json', JSON.stringify(o, null, 2), '```'];

  if (agents.includes('claude-code')) {
    const managed: Json = {};
    if (bypass) setAt(managed, 'permissions.disableBypassPermissionsMode', 'disable');
    const d = [...deny.map((x) => `Bash(${x} *)`), ...reads.map((g) => `Read(${g})`)];
    if (d.length) setAt(managed, 'permissions.deny', d);
    if (mcp) { managed.allowedMcpServers = mcp.map((serverName) => ({ serverName })); managed.allowManagedMcpServersOnly = true; }
    section('Claude Code', Object.keys(managed).length ? ['Managed settings can\'t be removed by project or user settings. Put this in `/Library/Application Support/ClaudeCode/managed-settings.json` (macOS), `/etc/claude-code/managed-settings.json` (Linux, WSL) or `C:\\Program Files\\ClaudeCode\\managed-settings.json` (Windows), or set it in the claude.ai admin console:', '', ...json(managed)] : []);
  }
  if (agents.includes('codex')) {
    const toml: string[] = [];
    if (bypass) toml.push('allowed_approval_policies = ["untrusted", "on-request"]', 'allowed_sandbox_modes = ["read-only", "workspace-write"]');
    const homeReads = reads.map((g) => g.replace(/\/\*\*$/, ''));
    if (homeReads.length) toml.push('', '[permissions.filesystem]', `deny_read = [${homeReads.map((g) => JSON.stringify(g.startsWith('**/') ? `/${g}` : g)).join(', ')}]`);
    if (deny.length) toml.push('', '[rules]', `prefix_rules = [${deny.map((d) => `{ pattern = [${tokens(d).map((t) => `{ token = ${JSON.stringify(t)} }`).join(', ')}], decision = "forbidden" }`).join(', ')}]`);
    if (mcp) for (const name of mcp) toml.push('', `[mcp_servers.${name}]`, 'identity = { command = "…" }   # or { url = "…" }: pin how this server is launched');
    section('Codex', toml.length ? ['A project `.codex/config.toml` can\'t forbid bypass modes or enforce read denies. Admin requirements can, and no config layer overrides them. Put this in `/etc/codex/requirements.toml` (or `%ProgramData%\\OpenAI\\Codex\\requirements.toml`, or deliver it by MDM or cloud-managed config):', '', '```toml', ...toml.filter((l, i, a) => !(l === '' && i === 0) && !(l === '' && a[i - 1] === '')), '```'] : []);
  }
  if (agents.includes('gemini')) {
    const sys: Json = {};
    if (bypass) setAt(sys, 'security.disableYoloMode', true);
    if (mcp) setAt(sys, 'mcp.allowed', mcp);
    const body = Object.keys(sys).length ? ['The repo\'s `.gemini/settings.json` only applies in trusted folders, and the system settings file wins over it. Put this in `/etc/gemini-cli/settings.json` (Linux), `/Library/Application Support/GeminiCli/settings.json` (macOS) or `C:\\ProgramData\\gemini-cli\\settings.json` (Windows):', '', ...json(sys)] : [];
    if (deny.length) body.push('', 'For command denies that users can\'t override, add an admin policy file in the root-owned system policies folder (for example `/etc/gemini-cli/policies/rookery.toml`):', '', '```toml', ...deny.flatMap((d) => ['[[rule]]', 'toolName = "run_shell_command"', `commandPrefix = ${JSON.stringify(d)}`, 'decision = "deny"', 'priority = 900', '']), '```');
    section('Gemini CLI', body);
  }
  if (agents.includes('cursor')) {
    const steps: string[] = [];
    if (bypass) steps.push('- Team dashboard → Run Mode / Auto Run Configuration: limit which modes members may use.');
    if (deny.length) steps.push(`- Team dashboard → command denylist: ${deny.map((d) => `\`${d}\``).join(', ')}. The repo's \`.cursor/cli.json\` only covers the CLI.`);
    if (mcp) steps.push(`- Team dashboard → MCP Configuration allowlist: ${mcp.map((m) => `\`${m}\``).join(', ') || '(empty: no servers)'}.`);
    if (reads.length) steps.push('- Team dashboard → Cursor Ignore Configuration, for paths outside the repo.');
    steps.push('- Workspace Trust is off by default, so every repo\'s hooks and allowlists apply on open. Turn it on with the `WorkspaceTrustEnabled` MDM policy.');
    section('Cursor', steps);
  }
  if (agents.includes('copilot')) {
    const managed: Json = {};
    if (bypass) setAt(managed, 'permissions.disableBypassPermissionsMode', 'disable');
    const d = [...deny.map((x) => `Shell(${x} *)`), ...reads.map((g) => `Read(${g})`)];
    if (d.length) setAt(managed, 'permissions.deny', d);
    if (mcp) managed.allowedMcpServers = mcp.map((serverName) => ({ serverName }));
    section('GitHub Copilot', Object.keys(managed).length ? ['A repo can\'t enforce these for Copilot: VS Code\'s `false` terminal rules only prompt. Enterprise managed settings apply to the CLI, VS Code and JetBrains. Commit this as `copilot/managed-settings.json` in your org\'s `.github-private` repo, or deliver it by MDM or `/etc/github-copilot/managed-settings.json`:', '', ...json(managed)] : []);
  }
  if (agents.includes('windsurf')) {
    const steps: string[] = [];
    if (bypass) steps.push('- Team settings → Maximum autonomy level: below Turbo.');
    if (mcp) steps.push(`- Team settings → MCP allowlist: ${mcp.map((m) => `\`${m}\``).join(', ') || '(empty: no servers)'}.`);
    if (deny.length) steps.push('- Cascade has no hard command deny list. Block commands with a `pre_run_command` hook that exits with code 2.');
    section('Windsurf', steps);
  }
  if (out.length === 6) out.push('Nothing in this policy needs an admin setting for the agents in this repo.', '');
  return out.join('\n');
}

/** A compact line diff for terminal output. */
export function lineDiff(before: string | null, after: string | null, context = 2): string[] {
  const a = before === null ? [] : before.replace(/\n$/, '').split('\n');
  const b = after === null ? [] : after.replace(/\n$/, '').split('\n');
  const n = a.length, m = b.length;
  const lcs: number[][] = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) lcs[i][j] = a[i] === b[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
  const ops: { op: ' ' | '-' | '+'; line: string }[] = [];
  let i = 0, j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) { ops.push({ op: ' ', line: a[i] }); i++; j++; }
    else if (j < m && (i >= n || lcs[i][j + 1] >= lcs[i + 1][j])) { ops.push({ op: '+', line: b[j] }); j++; }
    else { ops.push({ op: '-', line: a[i] }); i++; }
  }
  const keep = ops.map((o, k) => o.op !== ' ' || ops.slice(Math.max(0, k - context), k + context + 1).some((x) => x.op !== ' '));
  const out: string[] = [];
  ops.forEach((o, k) => { if (keep[k]) out.push(`${o.op} ${o.line}`); else if (keep[k - 1]) out.push('  …'); });
  return out;
}
